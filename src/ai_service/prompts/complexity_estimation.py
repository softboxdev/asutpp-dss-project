"""Промпт для оценки сложности."""

COMPLEXITY_ESTIMATION_SYSTEM = """Ты — эксперт по АСУ ТП.
Оцени сложность анализа текста. Отвечай одним числом от 0 до 1."""


def build_complexity_prompt(text: str) -> str:
    return f"""Оцени сложность анализа следующего фрагмента ТЗ АСУ ТП
с точки зрения извлечения требований к архитектуре:

\"\"\"
{text[:2000]}
\"\"\"

Ответь ТОЛЬКО числом от 0.0 (простой) до 1.0 (очень сложный):"""